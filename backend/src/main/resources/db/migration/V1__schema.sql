-- Green Basket 2.0: normalized schema (portable PostgreSQL / H2 PostgreSQL-mode SQL)
-- *_key columns hold the lower-cased value so uniqueness is case-insensitive on every database.

-- ============================================================ accounts
CREATE TABLE users (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username              VARCHAR(30)  NOT NULL,
    username_key          VARCHAR(30)  NOT NULL,
    full_name             VARCHAR(100) NOT NULL,
    email                 VARCHAR(150),
    role                  VARCHAR(20)  NOT NULL,
    password_hash         VARCHAR(255) NOT NULL,
    active                BOOLEAN      NOT NULL DEFAULT TRUE,
    must_change_password  BOOLEAN      NOT NULL DEFAULT FALSE,
    failed_attempts       INT          NOT NULL DEFAULT 0,
    locked_until          TIMESTAMP,
    last_login            TIMESTAMP,
    created_at            TIMESTAMP    NOT NULL,
    CONSTRAINT uq_users_username UNIQUE (username_key),
    CONSTRAINT ck_users_role CHECK (role IN ('MANAGER', 'ASSISTANT')),
    CONSTRAINT ck_users_failed CHECK (failed_attempts >= 0)
);

CREATE TABLE refresh_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT       NOT NULL,
    token_hash  VARCHAR(64)  NOT NULL,
    expires_at  TIMESTAMP    NOT NULL,
    revoked     BOOLEAN      NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP    NOT NULL,
    CONSTRAINT uq_refresh_token UNIQUE (token_hash),
    CONSTRAINT fk_refresh_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);
CREATE INDEX ix_refresh_user ON refresh_tokens (user_id);

CREATE TABLE password_reset_tokens (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id     BIGINT      NOT NULL,
    token_hash  VARCHAR(64) NOT NULL,
    expires_at  TIMESTAMP   NOT NULL,
    used        BOOLEAN     NOT NULL DEFAULT FALSE,
    created_at  TIMESTAMP   NOT NULL,
    CONSTRAINT uq_reset_token UNIQUE (token_hash),
    CONSTRAINT fk_reset_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE CASCADE
);

-- ============================================================ catalogue
CREATE TABLE categories (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(60) NOT NULL,
    name_key  VARCHAR(60) NOT NULL,
    CONSTRAINT uq_categories_name UNIQUE (name_key)
);

CREATE TABLE suppliers (
    id        BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name      VARCHAR(100) NOT NULL,
    name_key  VARCHAR(100) NOT NULL,
    phone     VARCHAR(40),
    email     VARCHAR(150),
    address   VARCHAR(255),
    CONSTRAINT uq_suppliers_name UNIQUE (name_key)
);

CREATE TABLE products (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name           VARCHAR(80)    NOT NULL,
    name_key       VARCHAR(80)    NOT NULL,
    category_id    BIGINT         NOT NULL,
    supplier_id    BIGINT,
    price          NUMERIC(12, 2) NOT NULL,
    cost           NUMERIC(12, 2) NOT NULL DEFAULT 0,
    quantity       INT            NOT NULL DEFAULT 0,
    reorder_level  INT            NOT NULL DEFAULT 10,
    expiry_date    DATE,
    active         BOOLEAN        NOT NULL DEFAULT TRUE,
    version        BIGINT         NOT NULL DEFAULT 0,
    created_at     TIMESTAMP      NOT NULL,
    updated_at     TIMESTAMP      NOT NULL,
    CONSTRAINT uq_products_name UNIQUE (name_key),
    CONSTRAINT fk_products_category FOREIGN KEY (category_id) REFERENCES categories (id),
    CONSTRAINT fk_products_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id),
    CONSTRAINT ck_products_price CHECK (price > 0),
    CONSTRAINT ck_products_cost CHECK (cost >= 0 AND cost <= price),
    CONSTRAINT ck_products_qty CHECK (quantity >= 0),
    CONSTRAINT ck_products_reorder CHECK (reorder_level >= 0)
);
CREATE INDEX ix_products_category ON products (category_id);
CREATE INDEX ix_products_supplier ON products (supplier_id);
CREATE INDEX ix_products_expiry ON products (expiry_date);

-- ============================================================ stock ledger
CREATE TABLE stock_movements (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id       BIGINT       NOT NULL,
    movement_type    VARCHAR(20)  NOT NULL,
    quantity_change  INT          NOT NULL,
    balance_after    INT          NOT NULL,
    user_id          BIGINT,
    user_name        VARCHAR(50)  NOT NULL,
    note             VARCHAR(255) NOT NULL DEFAULT '',
    created_at       TIMESTAMP    NOT NULL,
    CONSTRAINT fk_movement_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT fk_movement_user FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_movement_type CHECK (movement_type IN
        ('INITIAL', 'RECEIVE', 'SALE', 'VOID_RETURN', 'WASTAGE', 'CORRECTION')),
    CONSTRAINT ck_movement_balance CHECK (balance_after >= 0)
);
CREATE INDEX ix_movement_product ON stock_movements (product_id, created_at);
CREATE INDEX ix_movement_created ON stock_movements (created_at);

-- ============================================================ sales
CREATE TABLE sales (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    receipt_no        VARCHAR(20),
    cashier_id        BIGINT,
    cashier_name      VARCHAR(50)    NOT NULL,
    payment_method    VARCHAR(10)    NOT NULL,
    discount_percent  NUMERIC(5, 2)  NOT NULL DEFAULT 0,
    tax_rate          NUMERIC(5, 2)  NOT NULL DEFAULT 0,
    tendered          NUMERIC(12, 2) NOT NULL DEFAULT 0,
    voided            BOOLEAN        NOT NULL DEFAULT FALSE,
    voided_by         VARCHAR(50),
    voided_at         TIMESTAMP,
    void_reason       VARCHAR(255),
    created_at        TIMESTAMP      NOT NULL,
    CONSTRAINT uq_sales_receipt UNIQUE (receipt_no),
    CONSTRAINT fk_sales_cashier FOREIGN KEY (cashier_id) REFERENCES users (id) ON DELETE SET NULL,
    CONSTRAINT ck_sales_payment CHECK (payment_method IN ('CASH', 'CARD', 'MOBILE')),
    CONSTRAINT ck_sales_discount CHECK (discount_percent >= 0 AND discount_percent <= 100),
    CONSTRAINT ck_sales_tax CHECK (tax_rate >= 0 AND tax_rate <= 100),
    CONSTRAINT ck_sales_tendered CHECK (tendered >= 0)
);
CREATE INDEX ix_sales_created ON sales (created_at);
CREATE INDEX ix_sales_cashier ON sales (cashier_name);

CREATE TABLE sale_items (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sale_id        BIGINT         NOT NULL,
    product_id     BIGINT         NOT NULL,
    product_name   VARCHAR(80)    NOT NULL,
    category_name  VARCHAR(60)    NOT NULL,
    unit_price     NUMERIC(12, 2) NOT NULL,
    unit_cost      NUMERIC(12, 2) NOT NULL,
    quantity       INT            NOT NULL,
    CONSTRAINT fk_item_sale FOREIGN KEY (sale_id) REFERENCES sales (id) ON DELETE CASCADE,
    CONSTRAINT fk_item_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT ck_item_qty CHECK (quantity > 0),
    CONSTRAINT ck_item_price CHECK (unit_price >= 0 AND unit_cost >= 0)
);
CREATE INDEX ix_item_sale ON sale_items (sale_id);
CREATE INDEX ix_item_product ON sale_items (product_id);

-- ============================================================ purchasing
CREATE TABLE purchase_orders (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_number    VARCHAR(30)  NOT NULL,
    supplier_id  BIGINT,
    status       VARCHAR(12)  NOT NULL,
    notes        VARCHAR(255),
    created_by   VARCHAR(50)  NOT NULL,
    created_at   TIMESTAMP    NOT NULL,
    ordered_at   TIMESTAMP,
    received_at  TIMESTAMP,
    CONSTRAINT uq_po_number UNIQUE (po_number),
    CONSTRAINT fk_po_supplier FOREIGN KEY (supplier_id) REFERENCES suppliers (id),
    CONSTRAINT ck_po_status CHECK (status IN ('DRAFT', 'ORDERED', 'RECEIVED', 'CANCELLED'))
);
CREATE INDEX ix_po_status ON purchase_orders (status);

CREATE TABLE purchase_order_items (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    purchase_order_id  BIGINT         NOT NULL,
    product_id         BIGINT         NOT NULL,
    quantity_ordered   INT            NOT NULL,
    quantity_received  INT            NOT NULL DEFAULT 0,
    unit_cost          NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_poi_po FOREIGN KEY (purchase_order_id) REFERENCES purchase_orders (id) ON DELETE CASCADE,
    CONSTRAINT fk_poi_product FOREIGN KEY (product_id) REFERENCES products (id),
    CONSTRAINT ck_poi_qty CHECK (quantity_ordered > 0 AND quantity_received >= 0),
    CONSTRAINT ck_poi_cost CHECK (unit_cost >= 0)
);
CREATE INDEX ix_poi_po ON purchase_order_items (purchase_order_id);

-- ============================================================ audit + settings
CREATE TABLE activity_log (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username    VARCHAR(50)   NOT NULL,
    action      VARCHAR(60)   NOT NULL,
    details     VARCHAR(500)  NOT NULL DEFAULT '',
    created_at  TIMESTAMP     NOT NULL
);
CREATE INDEX ix_activity_created ON activity_log (created_at);

CREATE TABLE app_settings (
    setting_key    VARCHAR(60)  PRIMARY KEY,
    setting_value  VARCHAR(255) NOT NULL
);

